static long hyper_sample(RG *g, long good, long bad, long sample)
{
    long remaining_good = good, remaining_total, computed, total = good + bad;
    computed = sample > total / 2 ? total - sample : sample;
    remaining_total = total;
    while (computed > 0 && remaining_good > 0 && remaining_total > remaining_good) {
        --remaining_total;
        if (u64_tol(rg_interval(g, u64_l(remaining_total))) < remaining_good) --remaining_good;
        --computed;
    }
    if (remaining_total == remaining_good) remaining_good -= computed;
    return sample > total / 2 ? remaining_good : good - remaining_good;
}
