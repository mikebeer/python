/* positional dims (rand / randn) */
static Value rdims(Args *x, int off, RG *g, int legacy, const Dist *d)
{
    long shape[ND_MAXD], i;
    int nd = RN, k;
    Nd *r;
    if (nd == 0) return mkfloat(d->fn(g, legacy, 0.0, 0.0, 0.0));
    if (nd > ND_MAXD)
        throw_new(cls_ValueError, "maximum supported dimension for an ndarray is %d", ND_MAXD);
    for (k = 0; k < nd; k++) {
        shape[k] = need_long(RA(k), "dimension");
        if (shape[k] < 0) throw_new(cls_ValueError, "negative dimensions are not allowed");
    }
    r = nd_new(ND_FLOAT, nd, shape);
    for (i = 0; i < r->size; i++) r->dv[i] = d->fn(g, legacy, 0.0, 0.0, 0.0);
    return ndv(r);
}

/* integers: legacy randint (high exclusive, masked rejection) and Generator.integers (Lemire) */
static Value nr_ints(Args *x, int off, RG *g, int legacy)
{
    Value lov = rarg(x, off, 0, "low"), hiv = rarg(x, off, 1, "high"),
        szv = rarg(x, off, 2, "size");
    Value epv = legacy ? UNSET_V : kwget(x, "endpoint");
    long lo, hi, shape[ND_MAXD], i, cnt = 1;
    int nd, k;
    u64 rng;
    Nd *r;
    if (!np_has(lov))
        throw_new(cls_TypeError, "%s() missing required argument 'low' (pos 1)",
            legacy ? "randint" : "integers");
    if (!np_has(hiv)) { hi = need_long(lov, "low"); lo = 0; }
    else { lo = need_long(lov, "low"); hi = need_long(hiv, "high"); }
    if (!(np_has(epv) && py_truthy(epv))) hi--;      /* now inclusive */
    if (lo > hi) {
        if (np_has(epv) && py_truthy(epv)) throw_new(cls_ValueError, "low > high");
        throw_new(cls_ValueError, np_has(hiv) ? "low >= high" : "high <= 0");
    }
    rng = u64_sub(u64_l(hi), u64_l(lo));
    nd = rsize(szv, shape);
    if (nd >= 0) for (k = 0; k < nd; k++) cnt *= shape[k];
    if (nd < 0)
        return mkint(lo + u64_tol(rg_bounded(g, rng, legacy)));
    r = nd_new(ND_INT, nd, shape);
    for (i = 0; i < cnt; i++) r->iv[i] = lo + u64_tol(rg_bounded(g, rng, legacy));
    return ndv(r);
}

/* in-place Fisher-Yates of the first axis of an array / list (random_interval draws) */
static void shuffle_nd(Nd *a, RG *g)
{
    long n, row, i, j;
    Nd *tmp;
    if (a->nd == 0) throw_new(cls_TypeError, "shuffle: 0-d array");
    n = a->shape[0];
    row = n > 0 ? a->size / n : 0;
    tmp = nd_new(a->dt, 1, &row);
    for (i = n - 1; i > 0; i--) {
        j = u64_tol(rg_interval(g, u64_l(i)));
        if (j != i && row > 0) {
            nd_cp(tmp, 0, a, i * row, row);
            nd_cp(a, i * row, a, j * row, row);
            nd_cp(a, j * row, tmp, 0, row);
        }
    }
}
static Value nr_shuffle(Args *x, int off, RG *g)
{
    Value v;
    if (RN < 1) throw_new(cls_TypeError, "shuffle() missing 1 required positional argument: 'x'");
    v = RA(0);
    if (v.t == T_ND) shuffle_nd(AS_ND(v), g);
    else if (v.t == T_LIST) {
        List *l = AS_LIST(v);
        long i, j;
        for (i = l->n - 1; i > 0; i--) {
            Value t;
            j = u64_tol(rg_interval(g, u64_l(i)));
            t = l->a[i]; l->a[i] = l->a[j]; l->a[j] = t;
        }
    } else throw_new(cls_TypeError, "shuffle: unsupported type '%.40s'", type_name(v));
    return NONE_V;
}
static Value nr_permutation(Args *x, int off, RG *g)
{
    Value v;
    Nd *r;
    if (RN < 1)
        throw_new(cls_TypeError, "permutation() missing 1 required positional argument: 'x'");
    v = RA(0);
    if (v.t == T_INT) {
        long n = v.u.i, i;
        if (n < 0) throw_new(cls_ValueError, "negative dimensions are not allowed");
        r = nd_new1(ND_INT, n);
        for (i = 0; i < n; i++) r->iv[i] = i;
    } else {
        r = nd_from_value(v, -1);
        if (r->nd == 0) throw_new(cls_ValueError, "x must be an integer or at least 1-dimensional");
        if (v.t == T_ND) r = nd_astype(r, r->dt);
    }
    shuffle_nd(r, g);
    return ndv(r);
}
/* sum with Kahan compensation, as numpy's choice does */
static double kahan_sum(const double *d, long n)
{
    double sum = 0.0, c = 0.0, y, t;
    long i;
    for (i = 0; i < n; i++) {
        y = d[i] - c;
        t = sum + y;
        c = (t - sum) - y;
        sum = t;
    }
    return sum;
}
/* index of the first cdf entry greater than u (searchsorted side='right') */
static long cdf_search(const double *cdf, long n, double u)
{
    long lo = 0, hi = n;
    while (lo < hi) {
        long mid = (lo + hi) / 2;
        if (cdf[mid] <= u) lo = mid + 1; else hi = mid;
    }
    return lo;
}
static Value nr_choice(Args *x, int off, RG *g, int legacy)
{
    Value av = rarg(x, off, 0, "a"), szv = rarg(x, off, 1, "size"),
        rpv = rarg(x, off, 2, "replace");
    Value pv = rarg(x, off, 3, "p"), shv = legacy ? UNSET_V : kwget(x, "shuffle");
    Nd *src, *idx, *res;
    long n, cnt, i, j, shape[ND_MAXD], row;
    int nd, repl = 1, k, shuffle = 1;
    double *cum = NULL;
    List *objs = NULL;
    if (!np_has(av)) throw_new(cls_TypeError, "choice() missing required argument 'a' (pos 1)");
    if (np_has(rpv)) repl = py_truthy(rpv);
    if (np_has(shv)) shuffle = py_truthy(shv);
    if ((av.t == T_LIST || av.t == T_TUPLE) && AS_LIST(av)->n > 0 &&
        (AS_LIST(av)->a[0].t == T_STR || AS_LIST(av)->a[0].t == T_DICT ||
         AS_LIST(av)->a[0].t == T_SET || AS_LIST(av)->a[0].t == T_NONE)) {
        objs = AS_LIST(av);
        /* a sequence of objects: no ndarray dtype for it, choose by index */
        n = objs->n;
        src = NULL;
    } else if (av.t == T_INT) {
        n = av.u.i;
        src = NULL;
    } else {
        src = nd_from_value(av, -1);
        if (src->nd == 0)
            throw_new(cls_ValueError, "a must be a sequence or an integer, not %.40s",
                type_name(av));
        if (src->nd != 1 && legacy) throw_new(cls_ValueError, "a must be 1-dimensional");
        n = src->shape[0];
    }
    nd = rsize(szv, shape);
    cnt = 1;
    if (nd >= 0) for (k = 0; k < nd; k++) cnt *= shape[k];
    if (!src && n <= 0 && cnt != 0)
        throw_new(cls_ValueError, legacy ? "a must be greater than 0 unless no samples are taken" :
            "a must be a positive integer unless no samples are taken");
    if (src && n == 0 && cnt != 0)
        throw_new(cls_ValueError, legacy ? "'a' cannot be empty unless no samples are taken" :
            "a cannot be empty unless no samples are taken");
    if (np_has(pv)) {
        Nd *p = np_f(pv);
        double tot;
        if (p->nd != 1) throw_new(cls_ValueError, "'p' must be 1-dimensional");
        if (p->size != n) throw_new(cls_ValueError, "'a' and 'p' must have same size");
        tot = kahan_sum(p->dv, n);
        if (tot != tot) throw_new(cls_ValueError, "probabilities contain NaN");
        for (i = 0; i < n; i++)
            if (p->dv[i] < 0) throw_new(cls_ValueError, "probabilities are not non-negative");
        if (fabs(tot - 1.0) > 1.4901161193847656e-08)
            throw_new(cls_ValueError, "probabilities do not sum to 1");
        cum = (double *)xmalloc(sizeof(double) * (size_t)(n + 1));
        tot = 0.0;
        for (i = 0; i < n; i++) { tot += p->dv[i]; cum[i] = tot; }
        for (i = 0; i < n; i++) cum[i] /= tot;
    }
    if (!repl && cnt > n) {
        free(cum);
        throw_new(cls_ValueError,
            legacy ? "Cannot take a larger sample than population when 'replace=False'" :
            "Cannot take a larger sample than population when replace is False");
    }
    idx = nd_new1(ND_INT, cnt);
    if (repl) {
        if (cum) {
            for (i = 0; i < cnt; i++) idx->iv[i] = cdf_search(cum, n, rg_double(g));
        } else if (legacy) {
            u64 rg = u64_l(n - 1);
            for (i = 0; i < cnt; i++) idx->iv[i] = u64_tol(rg_bounded(g, rg, 1));
        } else {
            u64 rg = u64_l(n - 1);
            for (i = 0; i < cnt; i++) idx->iv[i] = u64_tol(rg_bounded(g, rg, 0));
        }
    } else if (cum) {
        double *w;
        long nuniq = 0, nz = 0;
        w = (double *)xmalloc(sizeof(double) * (size_t)(n + 1));
        {
            Nd *p = np_f(pv);
            for (i = 0; i < n; i++) { w[i] = p->dv[i]; if (w[i] > 0.0) nz++; }
        }
        if (nz < cnt) { free(w); free(cum);
            throw_new(cls_ValueError, "Fewer non-zero entries in p than size");
        }
        while (nuniq < cnt) {
            long m = cnt - nuniq, q, newn = 0;
            double *xs = (double *)xmalloc(sizeof(double) * (size_t)(m + 1));
            long *nw = (long *)xmalloc(sizeof(long) * (size_t)(m + 1));
            double tot = 0.0;
            for (i = 0; i < m; i++) xs[i] = rg_double(g);
            if (nuniq > 0) for (i = 0; i < nuniq; i++) w[idx->iv[i]] = 0.0;
            for (i = 0; i < n; i++) { tot += w[i]; cum[i] = tot; }
            for (i = 0; i < n; i++) cum[i] /= tot;
            for (i = 0; i < m; i++) nw[i] = cdf_search(cum, n, xs[i]);
            /* np.unique(return_index=True) then sorted by first occurrence */
            for (i = 0; i < m; i++) {
                int dup = 0;
                for (q = 0; q < i; q++) if (nw[q] == nw[i]) { dup = 1; break; }
                if (!dup) idx->iv[nuniq + newn++] = nw[i];
            }
            nuniq += newn;
            free(xs); free(nw);
        }
        free(w);
    } else if (legacy) {
        long *perm = (long *)xmalloc(sizeof(long) * (size_t)(n + 1));
        for (i = 0; i < n; i++) perm[i] = i;
        for (i = n - 1; i > 0; i--) {
            long t;
            j = u64_tol(rg_interval(g, u64_l(i)));
            t = perm[i]; perm[i] = perm[j]; perm[j] = t;
        }
        for (i = 0; i < cnt; i++) idx->iv[i] = perm[i];
        free(perm);
    } else {
        long size_i = cnt, pop = n;
        if (pop > 10000 && size_i > pop / (shuffle ? 50 : 20)) {
            long *arr = (long *)xmalloc(sizeof(long) * (size_t)(pop + 1));
            long stop = pop - size_i > 1 ? pop - size_i : 1;
            for (i = 0; i < pop; i++) arr[i] = i;
            for (i = pop - 1; i >= stop; i--) {
                long t;
                j = u64_tol(rg_bounded(g, u64_l(i), 0));
                t = arr[i]; arr[i] = arr[j]; arr[j] = t;
            }
            for (i = 0; i < size_i; i++) idx->iv[i] = arr[pop - size_i + i];
            free(arr);
        } else {
            /* Floyd's algorithm with an open-addressing hash set */
            unsigned long mask, setsize;
            long *hs;
            unsigned long m1 = (unsigned long)(1.2 * (double)size_i);
            m1 |= m1 >> 1; m1 |= m1 >> 2; m1 |= m1 >> 4; m1 |= m1 >> 8; m1 |= m1 >> 16;
            mask = m1;
            setsize = mask + 1UL;
            hs = (long *)xmalloc(sizeof(long) * (size_t)setsize);
            for (i = 0; i < (long)setsize; i++) hs[i] = -1;
            for (j = pop - size_i; j < pop; j++) {
                long val = u64_tol(rg_bounded(g, u64_l(j), 0));
                unsigned long loc = (unsigned long)val & mask;
                while (hs[loc] != -1 && hs[loc] != val) loc = (loc + 1UL) & mask;
                if (hs[loc] == -1) {
                    hs[loc] = val;
                    idx->iv[j - pop + size_i] = val;
                } else {
                    loc = (unsigned long)j & mask;
                    while (hs[loc] != -1) loc = (loc + 1UL) & mask;
                    hs[loc] = j;
                    idx->iv[j - pop + size_i] = j;
                }
            }
            free(hs);
            if (shuffle) {
                for (i = size_i - 1; i > 0; i--) {
                    long t;
                    j = u64_tol(rg_bounded(g, u64_l(i), 0));
                    t = idx->iv[i]; idx->iv[i] = idx->iv[j]; idx->iv[j] = t;
                }
            }
        }
    }
    free(cum);
    if (objs) {
        List *ol;
        if (nd < 0) return objs->a[idx->iv[0]];
        ol = list_new(cnt);
        for (i = 0; i < cnt; i++) list_push(ol, objs->a[idx->iv[i]]);
        return mklist(ol);
    }
    if (nd < 0) {
        if (!src) return mkint(idx->iv[0]);
        if (src->nd == 1) return nd_elem(src, idx->iv[0]);
        row = src->size / n;
        res = nd_new(src->dt, src->nd - 1, src->shape + 1);
        nd_cp(res, 0, src, idx->iv[0] * row, row);
        return ndv(res);
    }
    if (!src) {
        res = nd_new(ND_INT, nd, shape);
        for (i = 0; i < cnt; i++) res->iv[i] = idx->iv[i];
        return nd_ret(res);
    }
    row = n > 0 ? src->size / n : 0;
    {
        long rs[ND_MAXD];
        int rn = nd;
        for (k = 0; k < nd; k++) rs[k] = shape[k];
        for (k = 1; k < src->nd && rn < ND_MAXD; k++) rs[rn++] = src->shape[k];
        res = nd_new(src->dt, rn, rs);
    }
    for (i = 0; i < cnt; i++) nd_cp(res, i * row, src, idx->iv[i] * row, row);
    return nd_ret(res);
}

