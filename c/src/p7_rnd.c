static Value u64_value(u64 a)
{
    unsigned long d[4];
    d[0] = u64_lo(a) & 0xFFFFUL; d[1] = u64_lo(a) >> 16;
    d[2] = u64_hi(a) & 0xFFFFUL; d[3] = u64_hi(a) >> 16;
    return int_from_bin(d, 4, 0);
}
