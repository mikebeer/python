/* ---- standard distributions (numpy/random/src/distributions) ----------------------------
   Every function takes `legacy`: the RandomState algorithms (polar normal, inversion
   exponential) or the Generator ones (ziggurat). */
#define ZIG_NOR_R 3.6541528853610087963519472518
#define ZIG_NOR_INV_R 0.27366123732975827203338247596
#define ZIG_EXP_R 7.69711747013104972
static u64 zig_k(const unsigned long *t, int i) { return u64_c(t[2 * i], t[2 * i + 1]); }

static double legacy_gauss(RG *g)
{
    double f, x1, x2, r2, t;
    if (g->has_gauss) {
        t = g->gauss;
        g->has_gauss = 0;
        g->gauss = 0.0;
        return t;
    }
    do {
        x1 = 2.0 * rg_double(g) - 1.0;
        x2 = 2.0 * rg_double(g) - 1.0;
        r2 = x1 * x1 + x2 * x2;
    } while (r2 >= 1.0 || r2 == 0.0);
    f = sqrt(-2.0 * log(r2) / r2);
    g->gauss = f * x1;
    g->has_gauss = 1;
    return f * x2;
}
static double zig_normal(RG *g)
{
    for (;;) {
        u64 r = rg_next64(g), rabs;
        int idx = (int)(u64_lo(r) & 0xffUL), sign;
        double x, xx, yy;
        r = u64_shr(r, 8);
        sign = (int)(u64_lo(r) & 1UL);
        rabs = u64_and(u64_shr(r, 1), u64_c(0x000fffffUL, U32M));
        x = u64_dbl(rabs) * zig_nor_w[idx];
        if (sign) x = -x;
        if (u64_lt(rabs, zig_k(zig_nor_k, idx))) return x;
        if (idx == 0) {
            for (;;) {
                xx = -ZIG_NOR_INV_R * n_log1p(-rg_double(g));
                yy = -n_log1p(-rg_double(g));
                if (yy + yy > xx * xx)
                    return (u64_lo(u64_shr(rabs, 8)) & 1UL) ? -(ZIG_NOR_R + xx) : ZIG_NOR_R + xx;
            }
        } else {
            if ((zig_nor_f[idx - 1] - zig_nor_f[idx]) * rg_double(g) + zig_nor_f[idx] <
                exp(-0.5 * x * x)) return x;
        }
    }
}
static double zig_exp(RG *g)
{
    for (;;) {
        u64 ri = u64_shr(rg_next64(g), 3);
        int idx = (int)(u64_lo(ri) & 0xffUL);
        double x;
        ri = u64_shr(ri, 8);
        x = u64_dbl(ri) * zig_exp_w[idx];
        if (u64_lt(ri, zig_k(zig_exp_k, idx))) return x;
        if (idx == 0) return ZIG_EXP_R - n_log1p(-rg_double(g));
        if ((zig_exp_f[idx - 1] - zig_exp_f[idx]) * rg_double(g) + zig_exp_f[idx] < exp(-x))
            return x;
    }
}
static double std_normal(RG *g, int legacy) { return legacy ? legacy_gauss(g) : zig_normal(g); }
static double std_exp(RG *g, int legacy)
{
    return legacy ? -log(1.0 - rg_double(g)) : zig_exp(g);
}
static double std_gamma(RG *g, int legacy, double shape)
{
    double b, c, U, V, X, Y;
    if (shape == 1.0) return std_exp(g, legacy);
    if (shape == 0.0) return 0.0;
    if (shape < 1.0) {
        for (;;) {
            U = rg_double(g);
            V = std_exp(g, legacy);
            if (U <= 1.0 - shape) {
                X = pow(U, 1.0 / shape);
                if (X <= V) return X;
            } else {
                Y = -log((1.0 - U) / shape);
                X = pow(1.0 - shape + shape * Y, 1.0 / shape);
                if (X <= (V + Y)) return X;
            }
        }
    }
    b = shape - 1.0 / 3.0;
    c = 1.0 / sqrt(9.0 * b);
    for (;;) {
        do {
            X = std_normal(g, legacy);
            V = 1.0 + c * X;
        } while (V <= 0.0);
        V = V * V * V;
        U = rg_double(g);
        if (U < 1.0 - 0.0331 * (X * X) * (X * X)) return b * V;
        if (log(U) < 0.5 * X * X + b * (1.0 - V + log(V))) return b * V;
    }
}
static double d_loggam(double x)
{
    static const double a[10] = { 8.333333333333333e-02, -2.777777777777778e-03,
        7.936507936507937e-04, -5.952380952380952e-04, 8.417508417508418e-04,
        -1.917526917526918e-03, 6.410256410256410e-03, -2.955065359477124e-02,
        1.796443723688307e-01, -1.39243221690590e+00 };
    double x0, x2, lg2pi = 1.8378770664093453e+00, gl, gl0;
    long k, n;
    if (x == 1.0 || x == 2.0) return 0.0;
    n = x < 7.0 ? (long)(7.0 - x) : 0;
    x0 = x + (double)n;
    x2 = (1.0 / x0) * (1.0 / x0);
    gl0 = a[9];
    for (k = 8; k >= 0; k--) { gl0 *= x2; gl0 += a[k]; }
    gl = gl0 / x0 + 0.5 * lg2pi + (x0 - 0.5) * log(x0) - x0;
    if (x < 7.0) {
        for (k = 1; k <= n; k++) { gl -= log(x0 - 1.0); x0 -= 1.0; }
    }
    return gl;
}
static long poisson_mult(RG *g, double lam)
{
    long X = 0;
    double prod = 1.0, enlam = exp(-lam);
    for (;;) {
        prod *= rg_double(g);
        if (prod > enlam) X++; else return X;
    }
}
static long poisson_ptrs(RG *g, double lam)
{
    double slam = sqrt(lam), loglam = log(lam), b = 0.931 + 2.53 * slam, a, invalpha, vr, U, V, us;
    long k;
    a = -0.059 + 0.02483 * b;
    invalpha = 1.1239 + 1.1328 / (b - 3.4);
    vr = 0.9277 - 3.6224 / (b - 2.0);
    for (;;) {
        U = rg_double(g) - 0.5;
        V = rg_double(g);
        us = 0.5 - fabs(U);
        k = (long)floor((2.0 * a / us + b) * U + lam + 0.43);
        if (us >= 0.07 && V <= vr) return k;
        if (k < 0 || (us < 0.013 && V > us)) continue;
        if (log(V) + log(invalpha) - log(a / (us * us) + b) <=
            -lam + (double)k * loglam - d_loggam((double)k + 1.0)) return k;
    }
}
static long std_poisson(RG *g, double lam)
{
    if (lam >= 10.0) return poisson_ptrs(g, lam);
    if (lam == 0.0) return 0;
    return poisson_mult(g, lam);
}
static long binom_inversion(RG *g, long n, double p)
{
    double q = 1.0 - p, qn = exp((double)n * log(q)), np = (double)n * p, px, U;
    double lim = np + 10.0 * sqrt(np * q + 1.0);
    long X, bound = (long)(lim < (double)n ? lim : (double)n);
    X = 0;
    px = qn;
    U = rg_double(g);
    while (U > px) {
        X++;
        if (X > bound) {
            X = 0;
            px = qn;
            U = rg_double(g);
        } else {
            U -= px;
            px = (((double)n - (double)X + 1.0) * p * px) / ((double)X * q);
        }
    }
    return X;
}
static long binom_btpe(RG *g, long n, double p)
{
    double r, q, fm, p1, xm, xl, xr, c, laml, lamr, p2, p3, p4, a, u, v, s, F, rho, t, A, nrq;
    double x1, x2, f1, f2, z, z2, w, w2, x;
    long m, y, k, i;
    r = p < 1.0 - p ? p : 1.0 - p;
    q = 1.0 - r;
    fm = (double)n * r + r;
    m = (long)floor(fm);
    p1 = floor(2.195 * sqrt((double)n * r * q) - 4.6 * q) + 0.5;
    xm = (double)m + 0.5;
    xl = xm - p1;
    xr = xm + p1;
    c = 0.134 + 20.5 / (15.3 + (double)m);
    a = (fm - xl) / (fm - xl * r);
    laml = a * (1.0 + a / 2.0);
    a = (xr - fm) / (xr * q);
    lamr = a * (1.0 + a / 2.0);
    p2 = p1 * (1.0 + 2.0 * c);
    p3 = p2 + c / laml;
    p4 = p3 + c / lamr;
    nrq = (double)n * r * q;
    for (;;) {
        u = rg_double(g) * p4;
        v = rg_double(g);
        if (u <= p1) {
            y = (long)floor(xm - p1 * v + u);
            break;
        }
        if (u <= p2) {
            x = xl + (u - p1) / c;
            v = v * c + 1.0 - fabs((double)m - x + 0.5) / p1;
            if (v > 1.0) continue;
            y = (long)floor(x);
        } else if (u <= p3) {
            y = (long)floor(xl + log(v) / laml);
            if (y < 0 || v == 0.0) continue;
            v = v * (u - p2) * laml;
        } else {
            y = (long)floor(xr - log(v) / lamr);
            if (y > n || v == 0.0) continue;
            v = v * (u - p3) * lamr;
        }
        k = y > m ? y - m : m - y;
        if (!(k > 20 && (double)k < nrq / 2.0 - 1.0)) {
            s = r / q;
            a = s * ((double)n + 1.0);
            F = 1.0;
            if (m < y) {
                for (i = m + 1; i <= y; i++) F *= (a / (double)i - s);
            } else if (m > y) {
                for (i = y + 1; i <= m; i++) F /= (a / (double)i - s);
            }
            if (v > F) continue;
            break;
        }
        rho = ((double)k / nrq) * (((double)k * ((double)k / 3.0 + 0.625) + 0.16666666666666666) /
            nrq + 0.5);
        t = -(double)k * (double)k / (2.0 * nrq);
        A = log(v);
        if (A < t - rho) break;
        if (A > t + rho) continue;
        x1 = (double)y + 1.0;
        f1 = (double)m + 1.0;
        z = (double)n + 1.0 - (double)m;
        w = (double)n - (double)y + 1.0;
        x2 = x1 * x1; f2 = f1 * f1; z2 = z * z; w2 = w * w;
        if (A > xm * log(f1 / x1) + ((double)n - (double)m + 0.5) * log(z / w) +
            (double)(y - m) * log(w * r / (x1 * q)) +
            (13680. - (462. - (132. - (99. - 140. / f2) / f2) / f2) / f2) / f1 / 166320. +
            (13680. - (462. - (132. - (99. - 140. / z2) / z2) / z2) / z2) / z / 166320. +
            (13680. - (462. - (132. - (99. - 140. / x2) / x2) / x2) / x2) / x1 / 166320. +
            (13680. - (462. - (132. - (99. - 140. / w2) / w2) / w2) / w2) / w / 166320.)
            continue;
        break;
    }
    if (p > 0.5) y = n - y;
    return y;
}
static long std_binomial(RG *g, double p, long n, int legacy)
{
    if (!legacy && (n == 0 || p == 0.0)) return 0;
    if (p <= 0.5) {
        if (p * (double)n <= 30.0) return binom_inversion(g, n, p);
        return binom_btpe(g, n, p);
    }
    if ((1.0 - p) * (double)n <= 30.0) return n - binom_inversion(g, n, 1.0 - p);
    return binom_btpe(g, n, p);
}

