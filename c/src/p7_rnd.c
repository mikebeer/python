/* the 32-bit words of a non-negative integer (little endian); returns the count */
static long ss_int_words(Value v, unsigned long *out, long cap)
{
    unsigned long *d;
    int n, i;
    long cnt = 0;
    if (int_sign(v) < 0) throw_new(cls_ValueError, "expected non-negative integer");
    n = int_to_bin(v, &d);
    if (n == 0) { out[0] = 0UL; return 1; }
    for (i = 0; i < n; i += 2) {
        unsigned long lo = d[i] & 0xFFFFUL, hi = i + 1 < n ? d[i + 1] & 0xFFFFUL : 0UL;
        if (cnt >= cap) break;
        out[cnt++] = (hi << 16) | lo;
    }
    free(d);
    return cnt;
}
/* entropy words of an int / sequence of ints; the array is xmalloc'ed */
static long ss_entropy(Value v, unsigned long **out)
{
    unsigned long *w;
    long cnt = 0, cap, i;
    if (v.t == T_INT || v.t == T_BIG || v.t == T_BOOL) {
        cap = 1 + (int_bitlen(v) + 31) / 32;
        w = (unsigned long *)xmalloc(sizeof(unsigned long) * (size_t)cap);
        cnt = ss_int_words(v.t == T_BOOL ? mkint(v.u.i) : v, w, cap);
    } else if (v.t == T_LIST || v.t == T_TUPLE || v.t == T_ND) {
        Nd *a = v.t == T_ND ? AS_ND(v) : nd_from_value(v, ND_INT);
        if (a->dt != ND_INT && a->dt != ND_BOOL)
            throw_new(cls_TypeError, "SeedSequence expects int or sequence of ints for entropy not "
                "%.40s", type_name(v));
        cap = a->size * 3 + 1;
        w = (unsigned long *)xmalloc(sizeof(unsigned long) * (size_t)cap);
        for (i = 0; i < a->size; i++) {
            if (a->iv[i] < 0) { free(w); throw_new(cls_ValueError, "expected non-negative integer");
            }
            cnt += ss_int_words(mkint(a->iv[i]), w + cnt, cap - cnt);
        }
    } else {
        throw_new(cls_TypeError, "SeedSequence expects int or sequence of ints for entropy not "
            "%.40s", type_name(v));
        return 0;
    }
    *out = w;
    return cnt;
}
static void entropy_words(unsigned long *w, long n)
{
    unsigned char b[64];
    long i;
    host_urandom(b, 4 * n < 64 ? 4 * n : 64);
    for (i = 0; i < n; i++) {
        long k = (4 * i) % 60;
        w[i] = ((unsigned long)b[k] << 24) | ((unsigned long)b[k + 1] << 16) |
            ((unsigned long)b[k + 2] << 8) | (unsigned long)b[k + 3];
        w[i] ^= (unsigned long)i * 0x9e3779b9UL;
        w[i] &= U32M;
    }
}
static void rg_seed_pcg(RG *g, Value seed)
{
    unsigned long pool[4], st[8], *ent = NULL, tmp[4];
    long n;
    if (seed.t == T_UNSET || seed.t == T_NONE) {
        entropy_words(tmp, 4);
        ent = NULL;
        ss_pool(pool, tmp, 4);
    } else {
        n = ss_entropy(seed, &ent);
        ss_pool(pool, ent, n);
        free(ent);
    }
    ss_state(pool, st, 8);
    memset(g, 0, sizeof(RG));
    g->kind = 1;
    pcg_seed(g, u64_c(st[1], st[0]), u64_c(st[3], st[2]), u64_c(st[5], st[4]), u64_c(st[7], st[6]));
}
static void rg_seed_mt(RG *g, Value seed)
{
    memset(g, 0, sizeof(RG));
    g->kind = 0;
    if (seed.t == T_UNSET || seed.t == T_NONE) {
        unsigned long tmp[4], pool[4], key[MT_N];
        entropy_words(tmp, 4);
        ss_pool(pool, tmp, 4);
        ss_state(pool, key, MT_N);
        memcpy(g->mt, key, sizeof(g->mt));
        g->mpos = MT_N;
        return;
    }
    if (seed.t == T_INT || seed.t == T_BOOL || seed.t == T_BIG) {
        if (int_sign(seed) < 0 || int_cmp(seed, int_pow2(32)) >= 0)
            throw_new(cls_ValueError, "Seed must be between 0 and 2**32 - 1");
        {
            unsigned long w[3];
            ss_int_words(seed.t == T_BOOL ? mkint(seed.u.i) : seed, w, 3);
            mt_init32(g->mt, w[0]);
        }
        g->mpos = MT_N;
        return;
    }
    if (seed.t == T_FLOAT)
        throw_new(cls_TypeError, "Cannot cast array data from dtype('float64') to dtype('int64') "
            "according to the rule 'safe'");
    {
        Nd *a;
        unsigned long *key;
        long i;
        if (seed.t != T_ND && seed.t != T_LIST && seed.t != T_TUPLE)
            throw_new(cls_TypeError, "Seed must be an integer or an array of integers");
        a = seed.t == T_ND ? AS_ND(seed) : nd_from_value(seed, -1);
        if (a->dt == ND_FLOAT || a->dt == ND_COMPLEX)
            throw_new(cls_TypeError,
                "Cannot cast array data from dtype('float64') to dtype('int64')"
                " according to the rule 'safe'");
        if (a->size == 0) throw_new(cls_ValueError, "Seed must be non-empty");
        if (a->nd != 1) throw_new(cls_ValueError, "Seed array must be 1-d");
        key = (unsigned long *)xmalloc(sizeof(unsigned long) * (size_t)a->size);
        for (i = 0; i < a->size; i++) {
            if (a->iv[i] < 0 || (((unsigned long)a->iv[i] >> 16) >> 16) != 0) {
                free(key);
                throw_new(cls_ValueError, "Seed must be between 0 and 2**32 - 1");
            }
            key[i] = (unsigned long)a->iv[i];
        }
        mt_init_array(g->mt, key, a->size);
        g->mpos = MT_N;
        free(key);
    }
}
/* the state holder: an int array big enough for a RG */
static Value rg_holder(void)
{
    Nd *st = nd_new1(ND_INT, RG_LONGS);
    memset(st->iv, 0, sizeof(long) * (size_t)RG_LONGS);
    return ndv(st);
}
static RG *rg_get(Value iv)
{
    Value *sv;
    if (iv.t != T_INST) throw_new(cls_TypeError, "descriptor requires a random state object");
    sv = amap_get(&AS_INST(iv)->a, intern_c("_s"));
    if (!sv || sv->t != T_ND) throw_new(cls_TypeError, "uninitialised random state object");
    return (RG *)AS_ND(*sv)->iv;
}

/* ---- argument helpers: off = 0 for module functions, 1 for methods ---- */
#define RN (x->n - off)
#define RA(i) (x->a[off + (i)])
