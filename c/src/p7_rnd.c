static double f_unif01(RG *g, int l, double a, double b, double c) { (void)l; (void)a; (void)b;
    (void)c; return rg_double(g); }
static double f_stdnorm(RG *g, int l, double a, double b, double c) { (void)a; (void)b; (void)c;
    return std_normal(g, l); }
static double f_normal(RG *g, int l, double a, double b, double c) { (void)c;
    return a + b * std_normal(g, l); }
static double f_uniform(RG *g, int l, double a, double b, double c) { (void)l; (void)c;
    return a + (b - a) * rg_double(g); }
static double f_stdexp(RG *g, int l, double a, double b, double c) { (void)a; (void)b; (void)c;
    return std_exp(g, l); }
static double f_exp(RG *g, int l, double a, double b, double c) { (void)b; (void)c;
    return a * std_exp(g, l); }
static double f_stdgamma(RG *g, int l, double a, double b, double c) { (void)b; (void)c;
    return std_gamma(g, l, a); }
static double f_gamma(RG *g, int l, double a, double b, double c) { (void)c;
    return b * std_gamma(g, l, a); }
static double f_beta(RG *g, int l, double a, double b, double c)
{
    double Ga, Gb;
    (void)c;
    if (a <= 1.0 && b <= 1.0) {
        for (;;) {
            double U = rg_double(g), V = rg_double(g), X = pow(U, 1.0 / a), Y = pow(V, 1.0 / b),
                XpY = X + Y;
            if (XpY <= 1.0 && U + V > 0.0) {
                if (XpY > 0.0) return X / XpY;
                {
                    double logX = log(U) / a, logY = log(V) / b, logM = logX > logY ? logX : logY;
                    logX -= logM;
                    logY -= logM;
                    return exp(logX - log(exp(logX) + exp(logY)));
                }
            }
        }
    }
    Ga = std_gamma(g, l, a);
    Gb = std_gamma(g, l, b);
    return Ga / (Ga + Gb);
}
static double f_chisq(RG *g, int l, double a, double b, double c) { (void)b; (void)c;
    return 2.0 * std_gamma(g, l, a / 2.0); }
static double f_ncchisq(RG *g, int l, double df, double nonc, double c)
{
    (void)c;
    if (nonc != nonc) return nonc;
    if (nonc == 0.0) return 2.0 * std_gamma(g, l, df / 2.0);
    if (1.0 < df) {
        double Chi2 = 2.0 * std_gamma(g, l, (df - 1.0) / 2.0);
        double n = std_normal(g, l) + sqrt(nonc);
        return Chi2 + n * n;
    } else {
        long i = std_poisson(g, nonc / 2.0);
        return 2.0 * std_gamma(g, l, (df + 2.0 * (double)i) / 2.0);
    }
}
static double f_f(RG *g, int l, double dfnum, double dfden, double c)
{
    double num, den;
    (void)c;
    num = 2.0 * std_gamma(g, l, dfnum / 2.0) * dfden;
    den = 2.0 * std_gamma(g, l, dfden / 2.0) * dfnum;
    return num / den;
}
static double f_ncf(RG *g, int l, double dfnum, double dfden, double nonc)
{
    double t = f_ncchisq(g, l, dfnum, nonc, 0.0) * dfden;
    return t / (2.0 * std_gamma(g, l, dfden / 2.0) * dfnum);
}
static double f_cauchy(RG *g, int l, double a, double b, double c)
{
    double n, d;
    (void)a; (void)b; (void)c;
    n = std_normal(g, l);
    d = std_normal(g, l);
    return n / d;
}
static double f_t(RG *g, int l, double df, double b, double c)
{
    double num, denom;
    (void)b; (void)c;
    num = std_normal(g, l);
    denom = std_gamma(g, l, df / 2.0);
    return sqrt(df / 2.0) * num / sqrt(denom);
}
static double f_pareto(RG *g, int l, double a, double b, double c) { (void)b; (void)c;
    return l ? exp(std_exp(g, l) / a) - 1.0 : n_expm1(std_exp(g, l) / a); }
static double f_weibull(RG *g, int l, double a, double b, double c) { (void)b; (void)c;
    if (a == 0.0) return 0.0;
    return pow(std_exp(g, l), 1.0 / a); }
static double f_power(RG *g, int l, double a, double b, double c) { (void)b; (void)c;
    return pow(l ? 1.0 - exp(-std_exp(g, l)) : -n_expm1(-std_exp(g, l)), 1.0 / a); }
static double f_laplace(RG *g, int l, double loc, double scale, double c)
{
    double U;
    (void)l; (void)c;
    do U = rg_double(g); while (U <= 0.0);
    if (U >= 0.5) return loc - scale * log(2.0 - U - U);
    return loc + scale * log(U + U);
}
static double f_gumbel(RG *g, int l, double loc, double scale, double c)
{
    double U;
    (void)l; (void)c;
    U = 1.0 - rg_double(g);
    if (U < 1.0) return loc - scale * log(-log(U));
    return f_gumbel(g, l, loc, scale, 0.0);
}
static double f_logistic(RG *g, int l, double loc, double scale, double c)
{
    double U;
    (void)l; (void)c;
    do U = rg_double(g); while (U <= 0.0);
    return loc + scale * log(U / (1.0 - U));
}
static double f_lognormal(RG *g, int l, double mean, double sigma, double c) { (void)c;
    return exp(mean + sigma * std_normal(g, l)); }
static double f_rayleigh(RG *g, int l, double mode, double b, double c) { (void)b; (void)c;
    if (l) return mode * sqrt(-2.0 * n_log1p(-rg_double(g)));
    return mode * sqrt(2.0 * std_exp(g, l)); }
static double f_wald(RG *g, int l, double mean, double scale, double c)
{
    double mu_2l = mean / (2.0 * scale), Y = std_normal(g, l), X, U;
    (void)c;
    Y = mean * Y * Y;
    X = mean + mu_2l * (Y - sqrt(4.0 * scale * Y + Y * Y));
    U = rg_double(g);
    if (U <= mean / (mean + X)) return X;
    return mean * mean / X;
}
static double f_vonmises(RG *g, int l, double mu, double kappa, double c)
{
    double s, U, V, W, Y, Z, result, mod;
    int neg;
    (void)c;
    if (kappa != kappa) return kappa;
    if (kappa < 1e-8) return 3.141592653589793 * (2.0 * rg_double(g) - 1.0);
    if (kappa < 1e-5) s = 1.0 / kappa + kappa;
    else if (kappa <= 1e6) {
        double r = 1.0 + sqrt(1.0 + 4.0 * kappa * kappa), rho = (r - sqrt(2.0 * r)) / (2.0 * kappa);
        s = (1.0 + rho * rho) / (2.0 * rho);
    } else {
        result = mu + sqrt(1.0 / kappa) * std_normal(g, l);
        if (result < -3.141592653589793) result += 2.0 * 3.141592653589793;
        if (result > 3.141592653589793) result -= 2.0 * 3.141592653589793;
        return result;
    }
    for (;;) {
        U = rg_double(g);
        Z = cos(3.141592653589793 * U);
        W = (1.0 + s * Z) / (s + Z);
        Y = kappa * (s - W);
        V = rg_double(g);
        if (Y * (2.0 - Y) - V >= 0.0 || log(Y / V) + 1.0 - Y >= 0.0) break;
    }
    U = rg_double(g);
    result = acos(W);
    if (U < 0.5) result = -result;
    result += mu;
    neg = result < 0.0;
    mod = fabs(result);
    mod = fmod(mod + 3.141592653589793, 2.0 * 3.141592653589793) - 3.141592653589793;
    if (neg) mod *= -1.0;
    return mod;
}
static double f_triangular(RG *g, int l, double left, double mode, double right)
{
    double base = right - left, leftbase = mode - left, ratio = leftbase / base,
        leftprod = leftbase * base, rightprod = (right - mode) * base, U;
    (void)l;
    U = rg_double(g);
    if (U <= ratio) return left + sqrt(U * leftprod);
    return right - sqrt((1.0 - U) * rightprod);
}
static double f_poisson(RG *g, int l, double lam, double b, double c) { (void)l; (void)b; (void)c;
    return (double)std_poisson(g, lam); }
static double f_binomial(RG *g, int l, double n, double p, double c) { (void)c;
    return (double)std_binomial(g, p, (long)n, l); }
static double f_geometric(RG *g, int l, double p, double b, double c)
{
    (void)b; (void)c;
    if (p >= 0.333333333333333333333333) {
        double U = rg_double(g), sum = p, prod = p, q = 1.0 - p;
        long X = 1;
        while (U > sum) { prod *= q; sum += prod; X++; }
        return (double)X;
    }
    return ceil(-std_exp(g, l) / n_log1p(-p));
}
static double f_negbin(RG *g, int l, double n, double p, double c)
{
    double Y;
    (void)c;
    Y = (1.0 - p) / p * std_gamma(g, l, n);
    return (double)std_poisson(g, Y);
}
static double f_logseries(RG *g, int l, double p, double b, double c)
{
    double r = n_log1p(-p), U, V, q;
    long result;
    (void)l; (void)b; (void)c;
    for (;;) {
        V = rg_double(g);
        if (V >= p) return 1.0;
        U = rg_double(g);
        q = -n_expm1(r * U);
        if (V <= q * q) {
            result = (long)floor(1.0 + log(V) / log(q));
            if (result < 1 || V == 0.0) continue;
            return (double)result;
        }
        if (V >= q) return 1.0;
        return 2.0;
    }
}
static double f_zipf(RG *g, int l, double a, double b, double c)
{
    double am1 = a - 1.0, bb = pow(2.0, am1), U, V, X, T;
    (void)l; (void)b; (void)c;
    for (;;) {
        U = 1.0 - rg_double(g);
        V = rg_double(g);
        X = floor(pow(U, -1.0 / am1));
        if (X > 9.223372036854775807e18 || X < 1.0) continue;
        T = pow(1.0 + 1.0 / X, am1);
        if (V * X * (T - 1.0) / (bb - 1.0) <= T / bb) return X;
    }
}

