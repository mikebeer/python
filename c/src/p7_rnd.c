static u64 u64_and(u64 a, u64 b) { return a & b; }
static u64 u64_or(u64 a, u64 b) { return a | b; }
static unsigned long u64_lo(u64 a) { return (unsigned long)(a & 0xFFFFFFFFUL); }
static unsigned long u64_hi(u64 a) { return (unsigned long)((a >> 16) >> 16); }
static int u64_lt(u64 a, u64 b) { return !u64_ge(a, b); }
static int u64_eq(u64 a, u64 b) { return a == b; }
static int u64_iszero(u64 a) { return a == 0; }
#else
static u64 u64_and(u64 a, u64 b) { return u64_c(a.hi & b.hi, a.lo & b.lo); }
static u64 u64_or(u64 a, u64 b) { return u64_c(a.hi | b.hi, a.lo | b.lo); }
static unsigned long u64_lo(u64 a) { return a.lo; }
static unsigned long u64_hi(u64 a) { return a.hi; }
static int u64_lt(u64 a, u64 b) { return !u64_ge(a, b); }
static int u64_eq(u64 a, u64 b) { return a.hi == b.hi && a.lo == b.lo; }
static int u64_iszero(u64 a) { return a.hi == 0 && a.lo == 0; }
#endif
/* high 64 bits of the 128-bit product */
static u64 u64_mulhi(u64 a, u64 b)
{
    u64 m32 = u64_c(0UL, U32M);
    u64 a0 = u64_and(a, m32), a1 = u64_shr(a, 32), b0 = u64_and(b, m32), b1 = u64_shr(b, 32);
    u64 p00 = u64_mul(a0, b0), p01 = u64_mul(a0, b1), p10 = u64_mul(a1, b0), p11 = u64_mul(a1, b1);
    u64 mid = u64_add(u64_add(u64_shr(p00, 32), u64_and(p01, m32)), u64_and(p10, m32));
    return u64_add(u64_add(p11, u64_shr(p01, 32)), u64_add(u64_shr(p10, 32), u64_shr(mid, 32)));
}
/* 32 x 32 -> 64 bit product as (high, low) words */
static void mul32(unsigned long a, unsigned long b, unsigned long *hi, unsigned long *lo)
{
    unsigned long a0 = a & 0xFFFFUL, a1 = (a >> 16) & 0xFFFFUL, b0 = b & 0xFFFFUL,
        b1 = (b >> 16) & 0xFFFFUL;
    unsigned long p00 = a0 * b0, p01 = a0 * b1, p10 = a1 * b0, p11 = a1 * b1;
    unsigned long mid = (p00 >> 16) + (p01 & 0xFFFFUL) + (p10 & 0xFFFFUL);
    *lo = ((mid & 0xFFFFUL) << 16) | (p00 & 0xFFFFUL);
    *hi = (p11 + (p01 >> 16) + (p10 >> 16) + (mid >> 16)) & U32M;
}

/* ---- bit generators: MT19937 (kind 0) and PCG64 (kind 1) ------------------------------ */
#define MT_N 624
#define MT_M 397
typedef struct RG {
    int kind;
    unsigned long mt[MT_N];
    int mpos;
    u64 sh, sl, ih, il;              /* PCG64: 128-bit state and increment (high, low) */
    int has32;
    unsigned long u32;
    int has_gauss;                   /* legacy polar normal: cached second value */
    double gauss;
} RG;
#define RG_LONGS ((long)((sizeof(RG) + sizeof(long) - 1) / sizeof(long)))

/* init_genrand: Knuth's linear congruential seeding of the reference MT19937 */
static void mt_init32(unsigned long *mt, unsigned long s)
{
    int i;
    s &= U32M;
    for (i = 0; i < MT_N; i++) {
        mt[i] = s;
        s = (1812433253UL * (s ^ (s >> 30)) + (unsigned long)i + 1UL) & U32M;
    }
}
/* init_by_array of the reference implementation (key words are 32 bit) */
static void mt_init_array(unsigned long *mt, const unsigned long *key, long klen)
{
    long i = 1, j = 0, k;
    mt_init32(mt, 19650218UL);
    k = MT_N > klen ? MT_N : klen;
    for (; k; k--) {
        mt[i] = ((mt[i] ^ ((mt[i - 1] ^ (mt[i - 1] >> 30)) * 1664525UL)) + (key[j] & U32M) +
            (unsigned long)j) & U32M;
        i++; j++;
        if (i >= MT_N) { mt[0] = mt[MT_N - 1]; i = 1; }
        if (j >= klen) j = 0;
    }
    for (k = MT_N - 1; k; k--) {
        mt[i] = ((mt[i] ^ ((mt[i - 1] ^ (mt[i - 1] >> 30)) * 1566083941UL)) -
            (unsigned long)i) & U32M;
        i++;
        if (i >= MT_N) { mt[0] = mt[MT_N - 1]; i = 1; }
    }
    mt[0] = 0x80000000UL;
}
static unsigned long mt_next(RG *g)
{
    unsigned long y;
    unsigned long *mt = g->mt;
    if (g->mpos >= MT_N) {
        int kk;
        for (kk = 0; kk < MT_N - MT_M; kk++) {
            y = (mt[kk] & 0x80000000UL) | (mt[kk + 1] & 0x7fffffffUL);
            mt[kk] = mt[kk + MT_M] ^ (y >> 1) ^ ((y & 1UL) ? 0x9908b0dfUL : 0UL);
        }
        for (; kk < MT_N - 1; kk++) {
            y = (mt[kk] & 0x80000000UL) | (mt[kk + 1] & 0x7fffffffUL);
            mt[kk] = mt[kk + (MT_M - MT_N)] ^ (y >> 1) ^ ((y & 1UL) ? 0x9908b0dfUL : 0UL);
        }
        y = (mt[MT_N - 1] & 0x80000000UL) | (mt[0] & 0x7fffffffUL);
        mt[MT_N - 1] = mt[MT_M - 1] ^ (y >> 1) ^ ((y & 1UL) ? 0x9908b0dfUL : 0UL);
        g->mpos = 0;
    }
    y = mt[g->mpos++];
    y ^= (y >> 11);
    y ^= (y << 7) & 0x9d2c5680UL;
    y ^= (y << 15) & 0xefc60000UL;
    y ^= (y >> 18);
    return y & U32M;
}

/* PCG64 (XSL RR 128/64) with the default multiplier */
static void pcg_step(RG *g)
{
    u64 mh = u64_c(0x2360ED05UL, 0x1FC65DA4UL), ml = u64_c(0x4385DF64UL, 0x9FCCF645UL);
    u64 lo = u64_mul(g->sl, ml);
    u64 hi = u64_add(u64_add(u64_mulhi(g->sl, ml), u64_mul(g->sl, mh)), u64_mul(g->sh, ml));
    u64 lo2 = u64_add(lo, g->il);
    g->sh = u64_add(u64_add(hi, g->ih), u64_lt(lo2, lo) ? u64_ul(1UL) : u64_ul(0UL));
    g->sl = lo2;
}
static u64 rotr64(u64 v, int r);
static u64 pcg_next64(RG *g)
{
    pcg_step(g);
    return rotr64(u64_xor(g->sh, g->sl), (int)(u64_hi(g->sh) >> 26));
}
static u64 rotr64(u64 v, int r)
{
    if (r == 0) return v;
    return u64_or(u64_shr(v, r), u64_shl(v, 64 - r));
}
/* pcg_setseq_128_srandom_r: seed words s = (initstate hi, lo), q = (initseq hi, lo) */
static void pcg_seed(RG *g, u64 s_hi, u64 s_lo, u64 q_hi, u64 q_lo)
{
    u64 lo, c;
    g->sh = u64_ul(0UL); g->sl = u64_ul(0UL);
    g->ih = u64_or(u64_shl(q_hi, 1), u64_shr(q_lo, 63));
    g->il = u64_or(u64_shl(q_lo, 1), u64_ul(1UL));
    pcg_step(g);
    lo = u64_add(g->sl, s_lo);
    c = u64_lt(lo, g->sl) ? u64_ul(1UL) : u64_ul(0UL);
    g->sh = u64_add(u64_add(g->sh, s_hi), c);
    g->sl = lo;
    pcg_step(g);
    g->has32 = 0;
    g->u32 = 0;
}

static unsigned long rg_next32(RG *g)
{
    u64 n;
    if (g->kind == 0) return mt_next(g);
    if (g->has32) { g->has32 = 0; return g->u32; }
    n = pcg_next64(g);
    g->has32 = 1;
    g->u32 = u64_hi(n);
    return u64_lo(n);
}
static u64 rg_next64(RG *g)
{
    if (g->kind == 0) {
        unsigned long hi = mt_next(g);
        unsigned long lo = mt_next(g);
        return u64_c(hi, lo);
    }
    return pcg_next64(g);
}
static double rg_double(RG *g)
{
    if (g->kind == 0) {
        unsigned long a = mt_next(g) >> 5;
        unsigned long b = mt_next(g) >> 6;
        return ((double)a * 67108864.0 + (double)b) * (1.0 / 9007199254740992.0);
    }
    return u64_dbl(u64_shr(pcg_next64(g), 11)) * (1.0 / 9007199254740992.0);
}

/* ---- SeedSequence ------------------------------------------------------------------- */
static unsigned long ss_hashmix(unsigned long v, unsigned long *hc)
{
    v ^= *hc;
    *hc = (*hc * 0x931e8875UL) & U32M;
    v = (v * *hc) & U32M;
    v ^= v >> 16;
    return v;
}
static unsigned long ss_mix(unsigned long x, unsigned long y)
{
    unsigned long r = (0xca01f9ddUL * x - 0x4973f715UL * y) & U32M;
    r ^= r >> 16;
    return r;
}
/* the entropy pool (4 words) from nent 32-bit words */
static void ss_pool(unsigned long *pool, const unsigned long *ent, long nent)
{
    unsigned long hc = 0x43b0d7e5UL;
    long i, j;
    for (i = 0; i < 4; i++) pool[i] = ss_hashmix(i < nent ? ent[i] : 0UL, &hc);
    for (i = 0; i < 4; i++)
        for (j = 0; j < 4; j++)
            if (i != j) pool[j] = ss_mix(pool[j], ss_hashmix(pool[i], &hc));
    for (i = 4; i < nent; i++)
        for (j = 0; j < 4; j++) pool[j] = ss_mix(pool[j], ss_hashmix(ent[i], &hc));
}
/* n 32-bit output words */
static void ss_state(const unsigned long *pool, unsigned long *out, long n)
{
    unsigned long hc = 0x8b51f9ddUL, d;
    long i;
    for (i = 0; i < n; i++) {
        d = pool[i & 3] ^ hc;
        hc = (hc * 0x58f38dedUL) & U32M;
        d = (d * hc) & U32M;
        d ^= d >> 16;
        out[i] = d;
    }
}

/* ---- bounded integers (numpy's distributions.c) ------------------------------------- */
static u64 gen_mask(u64 max)
{
    u64 m = max;
    m = u64_or(m, u64_shr(m, 1)); m = u64_or(m, u64_shr(m, 2)); m = u64_or(m, u64_shr(m, 4));
    m = u64_or(m, u64_shr(m, 8)); m = u64_or(m, u64_shr(m, 16)); m = u64_or(m, u64_shr(m, 32));
    return m;
}
/* random_interval: the legacy shuffle / Generator.shuffle draw for [0, max] */
static u64 rg_interval(RG *g, u64 max)
{
    u64 mask, v;
    if (u64_iszero(max)) return max;
    mask = gen_mask(max);
    if (u64_hi(max) == 0) {
        do v = u64_and(u64_ul(rg_next32(g)), mask); while (u64_lt(max, v));
    } else {
        do v = u64_and(rg_next64(g), mask); while (u64_lt(max, v));
    }
    return v;
}
static unsigned long rg_lemire32(RG *g, unsigned long rng)
{
    unsigned long excl = (rng + 1UL) & U32M, hi, lo, thr;
    mul32(rg_next32(g), excl, &hi, &lo);
    if (lo < excl) {
        thr = (U32M - rng) % excl;
        while (lo < thr) mul32(rg_next32(g), excl, &hi, &lo);
    }
    return hi;
}
static u64 rg_lemire64(RG *g, u64 rng)
{
    u64 excl = u64_add(rng, u64_ul(1UL)), x = rg_next64(g), hi = u64_mulhi(x, excl),
        lo = u64_mul(x, excl), thr;
    if (u64_lt(lo, excl)) {
        thr = u64_mod(u64_sub(u64_max(), rng), excl);
        while (u64_lt(lo, thr)) {
            x = rg_next64(g);
            hi = u64_mulhi(x, excl);
            lo = u64_mul(x, excl);
        }
    }
    return hi;
}
/* random_bounded_uint64 with offset 0: a uniform draw from [0, rng] */
static u64 rg_bounded(RG *g, u64 rng, int masked)
{
    if (u64_iszero(rng)) return rng;
    if (u64_hi(rng) == 0) {
        unsigned long r = u64_lo(rng), v;
        if (r == U32M) return u64_ul(rg_next32(g));
        if (masked) {
            unsigned long mask = u64_lo(gen_mask(rng));
            do v = rg_next32(g) & mask; while (v > r);
            return u64_ul(v);
        }
        return u64_ul(rg_lemire32(g, r));
    }
    if (u64_eq(rng, u64_max())) return rg_next64(g);
    if (masked) {
        u64 mask = gen_mask(rng), v;
        do v = u64_and(rg_next64(g), mask); while (u64_lt(rng, v));
        return v;
    }
    return rg_lemire64(g, rng);
}

