{
    if (pos < RN) return RA(pos);
    return kwget(x, nm);
}
/* size argument -> shape; returns -1 for a scalar result */
static int rsize(Value sz, long *shape)
{
    if (!np_has(sz)) return -1;
    return shape_arg(sz, shape);
}
static int is_scalar_num(Value v)
{
    return v.t == T_INT || v.t == T_FLOAT || v.t == T_BOOL || v.t == T_BIG;
}

/* ---- distribution table ---------------------------------------------------------------- */
#define DREQ (-1.0e300)
typedef double (*DFn)(RG *g, int legacy, double a, double b, double c);
typedef const char *(*DChk)(double a, double b, double c);
typedef struct Dist {
    const char *name;
    int np;
    const char *pn[3];
    double dflt[3];
    DFn fn;
    int isint;
    DChk chk;
} Dist;

static Value dist_call(Args *x, int off, RG *g, int legacy, const Dist *d)
{
    Nd *pa[3];
    double pd[3];
    long shape[ND_MAXD], n = 1, i;
    int nd, k, anyarr = 0, ashape = -1;
    Value szv;
    Nd *r;
    for (k = 0; k < 3; k++) { pa[k] = NULL; pd[k] = 0.0; }
    for (k = 0; k < d->np; k++) {
        Value v = rarg(x, off, k, d->pn[k]);
        if (!np_has(v)) {
            if (d->dflt[k] == DREQ)
                throw_new(cls_TypeError, "%s() missing required argument '%s' (pos %d)", d->name,
                    d->pn[k], k + 1);
            pd[k] = d->dflt[k];
        } else if (is_scalar_num(v)) pd[k] = to_dbl(v);
        else {
            pa[k] = np_f(v);
            if (pa[k]->size == 1 && pa[k]->nd <= 1) { pd[k] = pa[k]->dv[0]; pa[k] = NULL; }
            else { anyarr = 1; if (ashape < 0) ashape = k; }
        }
    }
    szv = rarg(x, off, d->np, "size");
    nd = rsize(szv, shape);
    if (nd < 0 && anyarr) {
        Nd *src = pa[ashape];
        nd = src->nd;
        for (k = 0; k < nd; k++) shape[k] = src->shape[k];
    }
    if (nd >= 0) for (k = 0; k < nd; k++) n *= shape[k];
    for (k = 0; k < d->np; k++)
        if (pa[k] && pa[k]->size != n)
            throw_new(cls_ValueError, "shape mismatch: objects cannot be broadcast to a single "
                "shape");
    if (d->chk) {
        const char *msg = NULL;
        long cnt = nd < 0 ? 1 : n;
        for (i = 0; i < cnt && !msg; i++) {
            double a = pa[0] ? pa[0]->dv[i] : pd[0], b = pa[1] ? pa[1]->dv[i] : pd[1],
                c = pa[2] ? pa[2]->dv[i] : pd[2];
            msg = d->chk(a, b, c);
        }
        if (msg) throw_new(cls_ValueError, "%s", msg);
    }
    if (nd < 0) {
        double v = d->fn(g, legacy, pd[0], pd[1], pd[2]);
        return d->isint ? mkint((long)v) : mkfloat(v);
    }
    r = nd_new(d->isint ? ND_INT : ND_FLOAT, nd, shape);
    for (i = 0; i < n; i++) {
        double v = d->fn(g, legacy, pa[0] ? pa[0]->dv[i] : pd[0], pa[1] ? pa[1]->dv[i] : pd[1],
            pa[2] ? pa[2]->dv[i] : pd[2]);
        if (d->isint) r->iv[i] = (long)v; else r->dv[i] = v;
    }
    return ndv(r);
}

