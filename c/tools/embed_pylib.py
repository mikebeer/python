#!/usr/bin/env python3
"""Compile the pure-Python library tree into C byte arrays.

usage: python3 tools/embed_pylib.py [pylib-dir] > src/pylib_embed.c

Every *.py file below the directory becomes a set of arrays of decimal
byte values (ASCII codes, no character literals, so the data is the same
on an EBCDIC host; the interpreter translates through a literal set when it
reads a module).  The table pyemb_files[] maps "pkg/mod.py" to the chunks.
Every output line is at most 71 columns (the VM/370 deck limit)."""
import os
import sys

WIDTH = 71
CHUNK = 32000          # must match PYEMB_CHUNK in src/p0_os.c


def numlines(data):
    out, cur = [], " "
    for b in data:
        s = "%d," % b
        if len(cur) + len(s) > WIDTH:
            out.append(cur)
            cur = " "
        cur += s
    if cur != " ":
        out.append(cur)
    return out


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "..", "pylib")
    files = []
    for d, dirs, names in os.walk(root):
        dirs[:] = sorted(x for x in dirs if x != "__pycache__")
        for n in sorted(names):
            if n.endswith(".py"):
                full = os.path.join(d, n)
                files.append((os.path.relpath(full, root).replace(os.sep, "/"), full))
    files.sort()
    w = sys.stdout.write
    w("/* pylib_embed.c - GENERATED by tools/embed_pylib.py, do not edit.\n")
    w("   %d library modules as arrays of ASCII byte values. */\n" % len(files))
    table = []
    for i, (rel, full) in enumerate(files):
        with open(full, "rb") as f:
            data = f.read()
        if any(b == 0 for b in data):
            sys.exit("NUL byte in " + rel)
        chunks = [data[k:k + CHUNK] for k in range(0, len(data), CHUNK)]
        for j, ch in enumerate(chunks):
            w("static const unsigned char pyemb_%d_%d[] = {\n" % (i, j))
            w("\n".join(numlines(ch)) + "\n};\n")
        if chunks:
            w("static const unsigned char *const pyemb_%d[] = {\n" % i)
            w(" " + ", ".join("pyemb_%d_%d" % (i, j) for j in range(len(chunks))) + ", NULL\n};\n")
        table.append((rel, len(data), "pyemb_%d" % i if chunks else "NULL"))
    w("static const PyEmbFile pyemb_files[] = {\n")
    for rel, n, sym in table:
        w(' { "%s",\n   %dL, %s },\n' % (rel, n, sym))
    w(" { NULL, 0L, NULL }\n};\n")


if __name__ == "__main__":
    main()
