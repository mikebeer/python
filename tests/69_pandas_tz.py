import pandas as pd

ts = pd.Timestamp('2024-03-30 12:00', tz='Europe/Zurich')
print(ts)
print(repr(ts))
print(ts.tz, ts.utcoffset(), ts.tzname(), ts.value)
u = ts.tz_convert('UTC')
print(u, repr(u), u.hour)
print(ts + pd.Timedelta(days=1))
print(ts + pd.DateOffset(days=1))
print(ts + pd.Timedelta(hours=5))
ny = pd.Timestamp('2024-07-01 09:30').tz_localize('America/New_York')
print(ny, ny.tz_convert('Europe/Zurich'), ny.dst())
print(ny - ts, ny > ts, ny == ny.tz_convert('UTC'))
print(ny.tz_localize(None), ny.tz_convert(None))
print(pd.Timestamp('2024-01-01', tz='UTC'), repr(pd.Timestamp('2024-01-01', tz='UTC')))
print(pd.Timestamp('2024-06-01 10:00', tz='Asia/Kolkata'))
print(pd.Timestamp('2024-06-01 10:00', tz='Etc/GMT-3').utcoffset())
print(ts.isoformat(), ts.normalize(), ts.floor('h'), ts.date())
