import pandas as pd
import numpy as np
s = pd.Series([10, 20, 30], index=["a", "b", "c"])
print(s)
print(s["b"], s.iloc[0], s.loc["c"], s.values.tolist(), s.index.tolist(), len(s), s.sum(), s.mean(), s.max())
