# compiled patterns, match objects
p = re.compile(r"(?P<k>\w+)=(?P<v>\d*)")
m = p.match("key=12 rest")
print(m.group(), m.group(0), m.group(1, 2), m.group("k"), m.groups(), m.groupdict(), m.span("v"), m.start(2), m.end("k"), m.lastindex, m.lastgroup)
print(p.pattern, p.groups, sorted(p.groupindex.items()), p.flags, re.compile("a", re.I).flags, re.compile("(?i)a").flags)
m = p.match("k=")
print(m.group("v") == "", m.groups(), m.group(0), m.string, m.re is p)
m = re.match(r"(a)(b)?", "a")
print(m.groups(), m.groups("-"), m.group(2), m.span(2), m.start(2), m.groupdict())
print(p.search("zz a=1 b=2", 3).group(), p.findall("a=1 b=2"), p.sub(r"\2:\1", "a=1 b=2"), p.fullmatch("a=1"), p.fullmatch("a=1 "))
print(re.match("b", "abc", re.I) is None, re.compile("b").match("abc", 1).span(), re.compile("^b").search("abc", 1), re.compile("c$").search("abc", 0, 2))
print(re.match(r"(a)", "a").expand(r"<\1>"), re.escape("a.b*c d-e"), re.fullmatch(r"a|ab", "ab").group())
print(bool(re.match("a", "b")), re.match("a", "a") is not None, re.compile(p) is p)
# bigger inputs (no recursion per character)
