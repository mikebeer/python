# errors
for bad in [r"(", r")", r"[a", r"*a", r"a**", r"(?P<n>a)(?P<n>b)", r"\1", r"a{2,1}", r"(?<=a+)b", r"[z-a]", r"\q", r"(?P=x)", r"(?<n>a)"]:
    try:
        re.compile(bad)
        print("compiled", bad)
    except re.error:
        print("error", bad)
# findall / finditer / sub / split
print(re.findall(r"\d+", "a1b22c333"), re.findall(r"(\d)(\w)", "1a2b"), re.findall(r"(\d)", "1a2b"), re.findall(r"x*", "axb"))
print(re.findall(r"\w*", "ab cd"), re.findall(r"^\w", "ab\ncd", re.M), re.findall(r"(a)|(b)", "ab"))
print([m.span() for m in re.finditer(r"o", "foo boo")], [m.group(1) for m in re.finditer(r"(\w)o", "foo boo")])
print(re.sub(r"a", "b", "aaa"), re.sub(r"a", "b", "aaa", count=2), re.sub(r"x*", "-", "abxd"), re.sub(r"(?P<a>\w)(\w)", r"\g<a>-\2", "abcd"))
