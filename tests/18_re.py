# regex corner cases (expected output from CPython 3)
import re


def show(pat, s, flags=0):
    try:
        m = re.search(pat, s, flags)
    except re.error as e:
        print("error", pat)
        return
    if m is None:
        print(repr(pat), repr(s), "-> None")
    else:
        print(repr(pat), repr(s), "->", m.span(), m.group(), m.groups())


