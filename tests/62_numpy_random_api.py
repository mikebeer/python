import numpy as np

def show(label, v):
    if hasattr(v, 'tolist'):
        v = v.tolist()
        if isinstance(v, list):
            def r(x):
                if isinstance(x, list):
                    return [r(i) for i in x]
                return round(x, 9) if isinstance(x, float) else x
            v = r(v)
    elif isinstance(v, float):
        v = round(v, 9)
    print(label, v)

