import logging, logging.handlers, io, queue, errno, stat
t = io.StringIO()
th = logging.StreamHandler(t); th.setFormatter(logging.Formatter('%(levelname)s %(message)s'))
mh = logging.handlers.MemoryHandler(3, flushLevel=logging.ERROR, target=th)
lg = logging.getLogger('mem'); lg.propagate = False; lg.addHandler(mh); lg.setLevel(logging.DEBUG)
lg.info('a'); lg.info('b'); print(repr(t.getvalue()))
lg.error('boom'); print(repr(t.getvalue()))
q = queue.Queue()
lq = logging.getLogger('q'); lq.propagate = False; lq.addHandler(logging.handlers.QueueHandler(q)); lq.setLevel(logging.INFO)
lq.info('hello %s', 'x'); lq.warning('w')
print(q.qsize(), q.get_nowait().getMessage())
ql = logging.handlers.QueueListener(q, th); ql.start(); ql.stop()
print(repr(t.getvalue()))
print(errno.ENOENT, errno.errorcode[2], stat.S_ISDIR(0o040755), stat.filemode(0o100644), stat.S_IMODE(0o100755))
